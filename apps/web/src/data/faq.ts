/**
 * Ответ по ключу. Нужен листу оплаты: он показывает те же слова про бронь и
 * про способы оплаты, что стоят в FAQ. Копировать их вторым литералом
 * нельзя — при правке ТЗ разойдутся две строки в двух местах страницы.
 * Падает громко: опечатка в ключе — ошибка раскладки, как в `tariff()`.
 */
export function faqAnswer(id: string) {
  const found = FAQ.find((item) => item.id === id)
  if (!found) throw new Error(`Нет вопроса с ключом «${id}»`)
  return found.answer
}
