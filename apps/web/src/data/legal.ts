/**
 * Юридический блок подвала: документы и реквизиты продавца.
 *
 * Зачем он вообще нужен на этой странице — коротко, по закону:
 *
 * 1. **Политика обработки персональных данных.** 152-ФЗ, ч. 2 ст. 18.1:
 *    оператор обязан опубликовать документ, определяющий его политику
 *    обработки ПД, в открытом доступе. Обязанность возникает не от формы на
 *    странице, а от самого факта обработки — а обработка тут будет: оплата,
 *    переписка в WhatsApp, любые метрики. Документ должен быть доступен без
 *    регистрации, то есть ссылкой из подвала.
 *
 * 2. **Публичная оферта.** Страница продаёт услугу дистанционно (ст. 437 ГК:
 *    предложение с ценой и составом = оферта, акцепт — оплата). Правила
 *    продажи дистанционным способом и ЗоЗПП требуют до оплаты сообщить
 *    покупателю состав услуги, цену, порядок оплаты и порядок возврата. Ни
 *    один эквайринг не подключится без опубликованной оферты.
 *
 * 3. **Реквизиты продавца.** ЗоЗПП (ст. 8–10): наименование продавца (ИП или
 *    ООО), ИНН, ОГРН/ОГРНИП, адрес и способ связи должны быть на сайте до
 *    заключения договора, а не в переписке.
 *
 * ── Пока документов нет ──────────────────────────────────────────────────
 * У ссылки без `href` подвал рисует не ссылку, а приглушённую надпись:
 * блок стоит на месте, но никуда не ведёт. Тот же приём, что у кнопок
 * WhatsApp в тарифах, где нет номера (`whatsappHref` отдаёт `undefined`).
 * Битая ссылка на «Политику» хуже её отсутствия: она обещает документ,
 * которого нет.
 *
 * TODO: заполнить `href` — документы готовит заказчик (или его юрист).
 * TODO: заполнить `SELLER` — реквизиты. Пустые поля в строку не попадают,
 * поэтому можно заполнять по мере появления.
 * TODO: когда на странице появится форма или оплата, рядом с кнопкой нужен
 * отдельный непредзаполненный чекбокс согласия на обработку ПД со ссылкой
 * на политику, и отдельный — на рекламную рассылку (ст. 18 закона «О
 * рекламе»). Это не подвал, это форма; см. `docs/tz/03-QUESTIONS.md`, Q24.
 */

export type LegalDoc = {
  /** Ключ для React. */
  id: string
  /** Подпись ссылки. */
  title: string
  /** Адрес документа. Пустая строка — документа ещё нет. */
  href: string
}

export const LEGAL_DOCS: LegalDoc[] = [
  { id: 'privacy', title: 'Политика обработки персональных данных', href: '' },
  { id: 'offer', title: 'Публичная оферта', href: '' },
]

/**
 * Документ по ключу. Нужен листу оплаты: у чекбокса согласия ссылка на
 * политику, у кнопки — на оферту, и обе обязаны вести туда же, куда ведут
 * ссылки подвала. Падает громко: опечатка в ключе — ошибка раскладки.
 */
export function legalDoc(id: string): LegalDoc {
  const found = LEGAL_DOCS.find((doc) => doc.id === id)
  if (!found) throw new Error(`Нет документа с ключом «${id}»`)
  return found
}

/**
 * Реквизиты продавца. Заполняются по мере появления: пустые поля в строку
 * подвала не выводятся.
 *
 * `name` — «ИП Фамилия И. О.» или «ООО „Название“».
 */
export const SELLER = {
  name: '',
  inn: '',
  ogrn: '',
  email: '',
} as const

/** Строка реквизитов из заполненных полей. Пусто — блока в подвале нет. */
export function sellerLine() {
  return [
    SELLER.name,
    SELLER.inn && `ИНН ${SELLER.inn}`,
    SELLER.ogrn && `ОГРН ${SELLER.ogrn}`,
    SELLER.email,
  ]
    .filter(Boolean)
    .join(' · ')
}
