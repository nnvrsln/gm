import { useLayoutEffect, useRef, useState } from "react";

/**
 * Общий фон всех секций ниже героя: «Для кого?», «Автор обучения»,
 * «Программа», «Как проходит обучение», «Выбери свой тариф» и FAQ.
 *
 * Раньше свет жил внутри `AudienceSection` и начинался ровно на её границе:
 * секции стояли рядом, но каждая на своём фоне. Здесь слой один на обе —
 * зарево зарождается под фотографией стадиона, проходит через ленту
 * сегментов и гаснет к концу программы. Границы между секциями не видно.
 * (Секций было три, пока обложка «Для кого?» жила отдельной AboutSection;
 * теперь она внутри AudienceSection, и мерить нужно не её, а сам снимок.)
 *
 * **Свет рисуется одним элементом.** Раньше здесь были две зоны с
 * собственными масками — на «О курсе» с «Для кого» и на программу. Любая
 * пара зон даёт стык, а стык на градиентах — это ступенька: замер по
 * скриншоту показывал скачок яркости с 22 до 63 на границе секций, а после
 * подгонки — обратный, с 52 до 19. Подгонять такое бесполезно, поэтому зоны
 * убраны: четыре световых пятна лежат в одном свойстве `background`.
 *
 * **Координаты считаются от реальных высот секций, а не забиты числами.**
 * Сначала здесь стояли пиксели, снятые на макете 430px: граница секций —
 * 1110px. На телефоне экран уже, заголовки переносятся иначе, секции выше —
 * и тон, начинавшийся на 1112px, оказывался посреди «Для кого» и рисовал
 * поперёк неё видимую линию. Ровно та ступенька, которую было видно с
 * телефона и не видно на десктопе. Теперь высоты меряются на месте
 * (ResizeObserver), а стопы градиентов пересчитываются от них.
 *
 * Мерить приходится «Для кого», снимок стадиона внутри неё и отметку, на
 * которой начинается программа: всё это зависит от ширины экрана, но не
 * меняется во время работы. Высоту самой программы не трогаем принципиально —
 * у неё аккордеон, она скачет на сотни пикселей, и привязка к ней вернула бы
 * пересчёт фона на каждом кадре раскрытия.
 *
 * Рисунка в фоне нет намеренно. Пробовали разметку поля (дуги центрального
 * круга и линию штрафной) сначала на обе секции, потом только на «Для кого»:
 * поверх фотографии стадиона она читается грязью на снимке, а на тоне —
 * лишней геометрией рядом с кадрами сегментов. Остался чистый свет.
 *
 * Как встроен: компонент лежит в обёртке `<div className="relative">` вокруг
 * секций и **после** них в разметке; у обёртки стоит overflow-hidden, иначе
 * слой высотой 7600px делает прокручиваемым сам <main>. Слой с `z-[3]`
 * ложится выше фотографии и шторок «Для кого» (у них z-0…z-2), но ниже
 * текста секций: у «Для кого» контент поднят на z-10, у «Автора обучения» и
 * у программы — вся секция целиком.
 */
export function CourseBackdrop() {
  const root = useRef<HTMLDivElement>(null);
  // Стартовые значения — с макета 430px: до первого замера кадр успевает
  // отрисоваться, и с ними он выглядит верно.
  //
  // `about` — отметка, на которой кончается фотография стадиона и свету
  // можно разгораться. Раньше это была высота отдельной секции «О курсе»:
  // снимок обрезался её нижним краем, и «конец секции» и «конец фотографии»
  // были одним и тем же числом. Теперь обложка и лента слиты в одну секцию,
  // снимок уходит под карточки, и мерить надо сам снимок — элемент с
  // data-stadium внутри «Для кого».
  const [about, setAbout] = useState(451);
  const [seam, setSeam] = useState(712);
  // Верх «Программы». Раньше её не мерили: она шла сразу за «Для кого», и
  // seam был одновременно и концом одной секции, и началом другой. Между ними
  // встал «Автор обучения» (~880px), и нижние пятна, привязанные к seam,
  // остались под портретом — программа уходила в чёрное целиком.
  const [prog, setProg] = useState(712);

  useLayoutEffect(() => {
    const wrap = root.current?.parentElement;
    if (!wrap) return;
    const audienceEl = wrap.querySelector<HTMLElement>("#audience");
    const stadiumEl = wrap.querySelector<HTMLElement>(
      "#audience [data-stadium]",
    );
    const programEl = wrap.querySelector<HTMLElement>("#program");
    if (!audienceEl || !stadiumEl || !programEl) return;

    const update = () => {
      // offsetTop секции, а не ноль: слитая секция стоит первой в обёртке,
      // но если перед ней снова что-то появится, отсчёт не поедет.
      setAbout(audienceEl.offsetTop + stadiumEl.offsetHeight);
      // Нижняя граница «Для кого» — с неё начинается тон и разгорается свет.
      setSeam(audienceEl.offsetTop + audienceEl.offsetHeight);
      setProg(programEl.offsetTop);
    };
    update();

    // «Автор обучения» отдельно наблюдать не нужно: его высота входит в
    // offsetTop программы, а меняется он только вместе с шириной экрана —
    // тогда же меняется и высота «Для кого», за которой наблюдение уже есть.
    // Саму программу мерить по-прежнему нельзя: у неё аккордеон, и
    // ResizeObserver на ней пересчитывал бы фон на каждом кадре раскрытия.
    const observer = new ResizeObserver(update);
    observer.observe(audienceEl);
    observer.observe(stadiumEl);
    return () => observer.disconnect();
  }, []);

  return (
    <div
      ref={root}
      aria-hidden="true"
      // transform-gpu держит слой на GPU, а высота фиксированная, а не
      // inset-0: обёртка меняет высоту при каждом раскрытии модуля, и слой,
      // растянутый по ней, заставлял браузер каждый кадр заново считать
      // маску и градиенты на всю её площадь — отсюда были рывки.
      // 7600px — запас с расчётом на самый высокий случай. Замер обёртки:
      // 6117px на 430 и 6637 на 360 (последние 607 и 684 забирает FAQ);
      // раскрытый модуль программы добавляет до 400, раскрытый длинный
      // ответ в FAQ — ещё около 60. Худший случай — примерно 7100.
      // Пока база уходила в чёрный, нехватка высоты была не видна — под
      // слоем лежал тот же #05080b. Теперь база держит тон до самого низа, и
      // если слой кончится раньше обёртки, на его границе появится
      // ступенька: ровно это и случилось, когда слайд 6 добавил обёртке
      // 1335px, а слой остался в 5600. Слайд 8 добавил ещё около 620, и
      // прежние 7200 оставляли на 360 всего 160px запаса под аккордеоны.
      // Слайд 9 поднимал слой до 7800, но 01.09 владелец снял ту секцию со
      // страницы («убери пока этот блок»), и высота вернулась к 7600.
      // Вернётся секция — вместе с ней вернуть и запас, и пятно 13
      // (центр prog+5250, синее, плотность .16): без него секция ложится на
      // голый тон, как до этого ложились слайды 6 и 8.
      //
      // **Слой обязан лежать внутри клипующей коробки по размеру обёртки.**
      // Пока он висел прямо в обёртке своей полной высотой, обёртка
      // становилась прокручиваемой: её `overflow-hidden` не убирает
      // прокрутку, а лишь прячет полосу, и `scrollHeight` был 7600 против
      // `clientHeight` 6117. Браузер по якорю прокручивает КАЖДОГО
      // прокручиваемого предка цели, поэтому нажатие «Посмотреть тарифы»
      // прокручивало не только страницу, но и саму обёртку — на 1483px, —
      // и секции внутри неё уезжали вверх под обрез. Со стороны это
      // выглядело так, будто блок с кнопкой пропал.
      //
      // Внешняя коробка `inset-0` ничего не рисует, только режет: её высота
      // равна высоте обёртки, поэтому обёртке нечего прокручивать. Фиксированная
      // высота осталась у внутреннего слоя — на нём и держится
      // производительность.
      className="pointer-events-none absolute inset-0 z-[3] overflow-hidden"
    >
      <div className="absolute inset-x-0 top-0 h-[7600px] transform-gpu">
        {/* Маска гасит верх: пока идёт фотография стадиона, подмешивать к ней
          зарево нельзя. Свет набирает полную силу к нижнему краю снимка —
          там, где он и так растворяется по маске, потому переход и не
          читается. Стопы считаются от высоты снимка, а не от числа. */}
        <div
          style={{
            maskImage: `linear-gradient(180deg,transparent 0px,transparent ${Math.round(about * 0.63)}px,rgba(0,0,0,.45) ${Math.round(about * 0.82)}px,#000 ${about + 12}px,#000 100%)`,
            WebkitMaskImage: `linear-gradient(180deg,transparent 0px,transparent ${Math.round(about * 0.63)}px,rgba(0,0,0,.45) ${Math.round(about * 0.82)}px,#000 ${about + 12}px,#000 100%)`,
          }}
          className="absolute inset-0"
        >
          {/* Тональная база под программой и «Как проходит обучение» — первым
            слоем, свет ложится поверх. Стартует ровно цветом «Для кого»
            (#0c141d) на границе секций. Полупрозрачной её делать нельзя:
            своего фона у этих секций нет, и сквозь тон на границе просвечивал
            #05080b — секция обрывалась ступенькой (замер: 19 над границей
            против 8 под ней).

            **В чёрный база больше не уходит.** Раньше последним стопом стоял
            #05080b на prog+950 — то есть тон умирал на середине программы, и
            вся нижняя половина страницы лежала на чистом чёрном. Владелец:
            «фон стремится к чёрному, а хотелось бы, чтобы он продолжался с
            блока „Программа обучения“». Теперь база спускается до #0a1119
            (токен --color-panel) и дальше держится до низа слоя, а
            последний сход в bg-pitch рисует у себя внутри последняя секция
            страницы — «Выбери свой тариф» — так он едет вместе с её низом и не
            зависит от того, насколько раскрыт аккордеон программы. */}
          <div
            style={{
              backgroundImage: `linear-gradient(180deg,transparent 0px,transparent ${seam - 6}px,#0c141d ${seam}px,#0b121a ${seam + 450}px,#0a1119 ${prog + 900}px,#0a1119 100%)`,
            }}
            className="absolute inset-0"
          />

          {/* Все четыре пятна — в одном свойстве: браузер складывает их как
            единый фон, и швов между ними не бывает.

            1. Главное зарево от прожектора с фотографии стадиона: центр
               справа, чуть ниже нижнего края снимка.
            2. Отсвет слева у низа «Для кого».
            3. Продолжение диагонали в программе. Отсчёт от верха самой
               программы, а не от конца «Для кого»: между ними теперь стоит
               «Автор обучения». Верхний край пятна при этом заходит на низ
               портрета — тёмный участок между двумя световыми зонами не
               читается провалом.
            4. Дальний отсвет слева — не даёт последним модулям провалиться
               в чёрное при раскрытом аккордеоне.

            5-9. Цветная часть поля, от низа программы и ниже. Владелец
               попросил, чтобы фон «переливался цветами», и оттенки взяты не с
               потолка: это цвета категорий слайда 5 в том порядке, в каком
               они идут по странице. Холодная бирюза подхватывает низ
               программы, синий стоит под платформой и ступенями, лиловый
               разбивает длинный процессный блок, мята приходится на
               бесплатные доступы, золото — на то, что остаётся после.
               Центры чередуются по горизонтали, поэтому при прокрутке
               оттенок переходит по диагонали, а не гаснет и зажигается на
               месте.

               Альфа подобрана под контраст, а не на глаз: пик мяты даёт фон
               rgb(19,52,51), и белый текст в 55% на нём читается с запасом
               5.2:1 при норме 4.5. Золото ослаблено до .14 — на .17 тёплое
               пятно начинало читаться коричневым.

            Радиусы намеренно больше расстояний между центрами: пятна
            перекрываются, и яркость между ними меняется непрерывно.

            **Ни одно пятно не привязано к секции.** Свет здесь — сплошное
            поле на всю нижнюю половину страницы, и его центры отсчитываются
            от верха программы, который не двигается. Пробовали дать слайду 5
            собственный свет внутри секции — слой обрезался её верхним краем,
            и на стыке появлялась ступенька в 5 единиц яркости. */}
          <div
            style={{
              // Свет разгорается не раньше стыка. «Для кого» с недавних пор
              // поднята над этим слоем (z-10 на секции — иначе свет ложился
              // поверх её содержимого и глушил цвета), а фон у неё
              // непрозрачный. Значит выше стыка свет всё равно не виден, и без
              // этой маски он включался в первом же пикселе программы: замер
              // по краске давал (6,10,15) над границей и (25,40,63) под ней —
              // светлая полоса поперёк страницы. 190px хватает, чтобы подъём
              // прошёл незаметно.
              maskImage: `linear-gradient(180deg,transparent 0px,transparent ${seam}px,#000 ${seam + 190}px,#000 100%)`,
              WebkitMaskImage: `linear-gradient(180deg,transparent 0px,transparent ${seam}px,#000 ${seam + 190}px,#000 100%)`,
              backgroundImage: [
                `radial-gradient(560px 470px at 400px ${about + 32}px,rgba(112,164,236,.5) 0%,rgba(58,100,162,.28) 34%,rgba(22,40,66,.1) 64%,transparent 86%)`,
                `radial-gradient(300px 290px at 0px ${seam - 30}px,rgba(70,112,182,.3) 0%,rgba(28,52,86,.13) 46%,transparent 82%)`,
                `radial-gradient(520px 460px at 420px ${prog + 260}px,rgba(96,148,220,.34) 0%,rgba(50,88,144,.18) 36%,rgba(20,36,60,.07) 64%,transparent 88%)`,
                `radial-gradient(360px 340px at 20px ${prog + 800}px,rgba(64,104,170,.22) 0%,rgba(26,48,80,.1) 48%,transparent 84%)`,
                // Ниже — цветная часть поля. Центры идут в шахматном порядке
                // (право → лево → центр → право), поэтому при прокрутке оттенок
                // не просто меняется, а переходит по диагонали через экран.
                `radial-gradient(600px 520px at 20px ${prog + 1150}px,rgba(64,180,220,.16) 0%,rgba(28,86,110,.07) 44%,transparent 82%)`,
                `radial-gradient(640px 560px at 430px ${prog + 1820}px,rgba(96,148,220,.3) 0%,rgba(50,88,144,.14) 38%,transparent 84%)`,
                `radial-gradient(600px 540px at 0px ${prog + 2340}px,rgba(126,110,255,.18) 0%,rgba(52,46,110,.08) 44%,transparent 84%)`,
                `radial-gradient(620px 540px at 215px ${prog + 2760}px,rgba(63,224,176,.17) 0%,rgba(32,120,104,.07) 44%,transparent 84%)`,
                `radial-gradient(640px 560px at 400px ${prog + 3160}px,rgba(255,193,74,.14) 0%,rgba(150,110,50,.06) 42%,transparent 84%)`,
                // 10-11. Тарифы. Раньше цветное поле кончалось золотом на
                // prog+3160, а слайд 6 начинается на prog+3319 — вся секция
                // лежала на голом тоне, и «переливание» обрывалось ровно там,
                // где страница просит денег. Оттенки взяты из шкалы самой
                // секции: синий под лентой (в центре стоит ХИТ) и золото под
                // блоком обращений, как ВИП замыкает шкалу тарифов.
                `radial-gradient(620px 540px at 60px ${prog + 3620}px,rgba(96,148,220,.26) 0%,rgba(50,88,144,.12) 40%,transparent 84%)`,
                `radial-gradient(600px 520px at 400px ${prog + 4240}px,rgba(255,193,74,.11) 0%,rgba(150,110,50,.05) 42%,transparent 84%)`,
                // 12. FAQ. Та же история повторилась со слайдом 8: поле
                // кончалось на prog+4400, а секция занимает prog+4285…4892 на
                // 430 и prog+4682…5366 на 360 — то есть почти целиком лежала
                // на голом тоне, и «переливание» снова обрывалось на последней
                // секции страницы.
                //
                // Пятно одно и синее: синий — цвет нити у раскрытого вопроса,
                // единственный цвет самой секции. Золото сюда не идёт, оно
                // этажом выше замыкает шкалу тарифов, и второй тёплый круг
                // подряд читался бы продолжением тарифов, а не новым блоком.
                //
                // Центр на prog+4700 — компромисс между двумя ширинами: на 430
                // он приходится на низ секции, на 360 на её середину, и при
                // радиусе 560 накрыты обе. Плотность .22 ниже тарифных .26:
                // секция справочная, светить на ней громче, чем на тарифах,
                // незачем. Ниже цвета нет намеренно — там FAQ гасит себя в
                // bg-pitch собственным слоем, и подсвечивать сход нечем.
                `radial-gradient(620px 560px at 110px ${prog + 4700}px,rgba(96,148,220,.22) 0%,rgba(50,88,144,.1) 40%,transparent 84%)`,
              ].join(","),
            }}
            className="absolute inset-0"
          />
        </div>
      </div>
    </div>
  );
}
