import coachStand from '../assets/coach-stand.webp'
import { ACHIEVEMENTS } from '../data/achievements'
import { Eyebrow } from './Eyebrow'

/**
 * Слайд 3 ТЗ «Автор обучения».
 *
 * Подача — вариант 01 «Досье на поле» с макетной `/coach.html`, выбран
 * владельцем из восьми. До него перепробованы и отклонены: портрет отдельной
 * колонкой и широкая фотополоса с текстом по низу, по верху и по центру.
 * Беда у всех трёх была одна — фотография и текст оставались двумя разными
 * блоками, которые приходилось выравнивать друг относительно друга.
 *
 * Здесь выравнивать нечего: кадр в полный рост (`coach-stand.webp` из
 * присланного 31.08 `docs/newbg.png`) лежит подложкой всей секции, а не
 * вставкой внутри неё. Фигура на снимке стоит в правой половине, левые 55%
 * ширины — чистая темнота: это готовая колонка, в которую садится весь
 * текст. Отсюда и геометрия ТЗ «справа его фото, а слева текст» — без
 * границы между колонками и без единой рамки.
 *
 * Высоту секции задаёт содержимое, а снимок растягивается по ней
 * (`object-cover`, якорь 78% по горизонтали). Так фигура всегда во весь рост
 * секции: шесть регалий идут вдоль неё, а не свисают ниже ботинок — это была
 * претензия владельца к прежней версии, где снимок масштабировался по ширине
 * и на 360px кончался на четвёртой строке.
 *
 * Якорь 78%, а не 100%: при растяжении по высоте кадр шире экрана и часть
 * его срезается по горизонтали. С якорем у правого края срезался бы весь
 * пустой левый угол, фигура уезжала бы влево и лезла в текст (замер на 360:
 * левый край фигуры на 27% ширины). На 78% срезается и справа тоже —
 * стадион, а не фигура, — и фигура остаётся в правой половине на обеих
 * ширинах. Плата: на узком экране кадр приближен сильнее, лицо крупнее.
 *
 * Три слоя поверх снимка, у каждого своя работа:
 *   1. Горизонтальная шторка держит левую колонку. Без неё текст ложится на
 *      подсвеченную кромку газона. Плотность растёт книзу — у градиента есть
 *      вертикальная маска: вверху кадра лицо и гасить его нельзя, внизу по
 *      фигуре идут регалии и без шторки они теряются на пальто.
 *   2. Верхняя стыкует секцию с «Для кого». Стартует ровно `#0c141d` — это
 *      цвет, которым `CourseBackdrop` красит границу секций (см. комментарий
 *      там). Цвет в цвет, поэтому шва не видно.
 *   3. Нижняя гасит кадр в `#0b121a` — тон той же базы примерно 450px ниже
 *      стыка, то есть там, где секция кончается и начинается «Программа».
 * Требование владельца: фон страницы должен идти сквозь секцию бесшовно, как
 * на слайде 2. Масок (`.coach-scene-*`) здесь больше нет — они растворяли
 * прежний кадр-полосу, а фон-подложку растворять нечем: под ней сразу тон
 * страницы, и стык делается цветом, а не прозрачностью.
 *
 * Регалии набраны Bebas-капслоком 15px с пояснением 12px: колонка узкая,
 * прежние 21px в неё не влезают. У каждой своя предметная фотография из
 * листа заказчика — см. комментарий в `src/data/achievements.ts`.
 *
 * Вводного абзаца («более 50 лет в большом футболе») нет: в ТЗ его нет, а
 * тексты берём дословно из 01-SPEC.md (Q8).
 *
 * z-10 обязателен: общий свет CourseBackdrop лежит слоем z-[3] поверх
 * потока, и его тональная база непрозрачна — без подъёма секция оказывается
 * под ней. Так же сделано в «Для кого» и в «Программе».
 */
export function CoachSection() {
  return (
    <section
      id="coach"
      aria-labelledby="coach-title"
      className="section-rhythm relative z-10 overflow-hidden px-5"
    >
      {/* Кадр декоративен для скринридера: всё, что на нём есть, стоит рядом
          текстом — имя в заголовке, регалии списком. Про масштаб и якорь 78%
          — в комментарии к компоненту. */}
      <div className="pointer-events-none absolute inset-0">
        <img
          src={coachStand}
          alt=""
          aria-hidden="true"
          className="h-full w-full select-none object-cover object-[78%_50%]"
        />
        {/* Шторка под текст. Держит полную плотность до 57% ширины — это
            текстовая колонка — и отпускает к 84%, где лицо. Раньше отпускала
            к 94% и съедала часть яркости лица.
            Плотность растёт ещё и книзу: вверху кадра лицо, гасить его
            нельзя, а внизу по фигуре идут регалии. Отсюда вертикальная маска
            — первые 30% высоты градиент работает в треть силы. */}
        <div className="absolute inset-0 bg-[linear-gradient(90deg,rgba(5,8,11,.95)_0%,rgba(5,8,11,.9)_42%,rgba(5,8,11,.62)_57%,rgba(5,8,11,.14)_71%,transparent_84%)] [mask-image:linear-gradient(180deg,rgba(0,0,0,.34)_0%,rgba(0,0,0,.5)_16%,#000_30%,#000_100%)] [-webkit-mask-image:linear-gradient(180deg,rgba(0,0,0,.34)_0%,rgba(0,0,0,.5)_16%,#000_30%,#000_100%)]" />
        {/* Верхняя шторка стыкует секцию с «Для кого»: стартует ровно
            `#0c141d` — цвет, которым CourseBackdrop красит границу секций.
            Она же приглушает лицо примерно вдвое (замер: 68 против 140 в
            файле). Пробовали убрать и увести стык внутрь кадра, нарастив
            канву вверх на 220px: лицо стало 130, но фигура опустилась и
            разметка съехала — владелец откатил. Трогать этот слой можно
            только вместе с раскладкой. */}
        <div className="absolute inset-x-0 top-0 h-28 bg-[linear-gradient(180deg,#0c141d_0%,rgba(12,20,29,.62)_46%,transparent_100%)]" />
        {/* Низ кадра уходит в тон страницы: `CourseBackdrop` красит эту
            отметку примерно #0b121a, поэтому граница фотографии не читается
            линией. */}
        <div className="absolute inset-x-0 bottom-0 h-44 bg-[linear-gradient(180deg,transparent_0%,rgba(11,18,26,.72)_54%,#0b121a_100%)]" />
      </div>

      <div className="relative">
        <Eyebrow line={false} className="text-[10px]">
          Автор обучения
        </Eyebrow>
        {/* Каждое слово отдельной строкой — не подпорка под перенос, а форма
            подписи в досье: колонка узкая, и «Гаджи Муслимович» в одну строку
            в неё не встаёт ни на 430, ни на 360. Жёстких <br> при этом нет —
            правило «Heading Line Balance» из ui-ux-pro-max. */}
        <h2 id="coach-title" className="section-title mt-2 text-[30px] uppercase leading-[.92] tracking-title">
          <span className="block">Гаджиев</span>
          <span className="block">Гаджи</span>
          <span className="block">Муслимович</span>
        </h2>

        {/* «Далее — списком регалии» (ТЗ). Колонка 58% — компромисс, а не
            граница фигуры: после того как кадр стали растягивать по высоте,
            фигура начинается на 51% ширины на 430 и на 40% на 360, то есть
            нижние строки частично ложатся на пальто и брюки. Там темно, и
            шторка добавляет плотности книзу, поэтому текст читается; уводить
            колонку левее нельзя — «МУСЛИМОВИЧ» и так занимает 144px из 180
            доступных на 360. */}
        <ol className="mt-6 w-[58%] space-y-3.5">
          {ACHIEVEMENTS.map((item) => (
            <li key={item.title} className="flex items-start gap-2.5">
              {/* Размер задан обеими сторонами — иначе строка прыгает после
                  загрузки кадра (CLS). Скругление повторяет то, что вырезано
                  в самом файле альфой. */}
              <img
                src={item.icon}
                alt=""
                aria-hidden="true"
                loading="lazy"
                width={36}
                height={36}
                className="mt-0.5 size-9 shrink-0 select-none rounded-lg"
              />
              <div className="min-w-0">
                {/* Bebas инлайновым стилем, а не утилитой font-[...]: имя
                    шрифта с пробелами Tailwind как arbitrary-значение не
                    разбирает. */}
                <p
                  style={{ fontFamily: '"Bebas Neue Cyrillic", "Bahnschrift", sans-serif' }}
                  className="text-[15px] uppercase leading-[1.05] tracking-title text-white"
                >
                  {item.title}
                </p>
                <p className="mt-0.5 text-[12px] leading-[1.3] text-white/55">{item.detail}</p>
              </div>
            </li>
          ))}
        </ol>
      </div>
    </section>
  )
}
