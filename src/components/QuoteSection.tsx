import type { CSSProperties } from 'react'
import coachBand from '../assets/coach-band.webp'
import { QUOTE } from '../data/quote'

/**
 * Слайд 9 ТЗ «Финальная цитата» — последняя секция страницы.
 *
 * Подача 02 «Врезка с обтеканием» с макетной `/quote.html`, выбор владельца
 * из третьего захода. До неё отклонены восемь подач: текст и кадр друг над
 * другом (три), кадр колонкой рядом с текстом (две), кадр фоном блока (две)
 * и «манифест» с цитатой крупным Bebas. Все они спорили об одном — где
 * стоит фотография относительно колонки текста; здесь вопрос снят самим
 * приёмом.
 *
 * ── Что задано и не обсуждается ──────────────────────────────────────────
 * В ТЗ по этому слайду нет ничего, кроме строки «мотивационная цитата и
 * жизнеутверждающее фото» (Q20). Текст владелец передал сам 01.09 — это блок
 * с работающего `gadjiev.pro`, лежит дословно в `data/quote.ts`. Кадр назван
 * там же: `coach-band.webp`, широкая полоса 1100×511 из первой партии.
 *
 * ── Устройство подачи ────────────────────────────────────────────────────
 * Журнальный приём: снимок врезан в текст, и текст его обтекает. Направление
 * сверено со скиллом ui-ux-pro-max — стиль `editorial-grid-magazine`, откуда
 * взяты буквица, врезка с обтеканием и печатные линейки вместо рамок.
 *
 * Обтекание снимает то, обо что спотыкались все прошлые подачи: колонка
 * рядом с фотографией была узкой на всю высоту блока, и цитата в 215 знаков
 * шла в ней десятью строками. Здесь узкими остаются только первые четыре
 * строки — дальше текст идёт во всю ширину, снимок отдаёт место, как только
 * кончился.
 *
 * Врезка задана долей ширины (44%), а не пикселями: на 360 фиксированные
 * 150px забирали почти половину строки и обтекающие строки рвались на два-три
 * слова. Кадрирование по лицу — якорь 70% по горизонтали, 38% по вертикали.
 *
 * Кавычка работает буквицей: `float` рядом с первым словом, как
 * `::first-letter` в печатной вёрстке.
 *
 * Ни одного пикселя текста поверх фотографии здесь нет: читаемость не
 * зависит от того, что на кадре, и контраст держится на фоне страницы.
 *
 * ── Чем секция пришита к FAQ над собой ───────────────────────────────────
 * Первая версия стояла на странице чужой: карточка с волосяной рамкой и
 * скруглением, цитата 16px и своя линейка byline — «как будто бы просто
 * вкинули блок» (владелец). Ниже тарифов на странице нет ни одной рамки, а
 * FAQ построен на волосяных линиях, капслоке и синей нити.
 *
 * Поэтому вся материя секции взята у FAQ:
 *   — сверху та же волосяная линия `white/[.07]`, что делит вопросы, — цитата
 *     читается последней строкой того же списка;
 *   — слева синяя нить 2px с тем же затуханием, что метит раскрытый вопрос,
 *     и тот же отступ `pl-3.5`;
 *   — имя набрано ровно как вопрос: Bebas-капслок 17px, трекинг 1px, цвет
 *     `#EAF2FF` — цвет раскрытого вопроса;
 *   — у врезки больше нет ни рамки, ни скругления: края растворяются масками
 *     в фон, как снимки слайдов 2 и 3, а сам кадр приглушён до 0.86 —
 *     прожекторы на нём были ярче всего, что осталось на этом этаже.
 *
 * ── Как секция сидит на фоне ─────────────────────────────────────────────
 * Своего фона у секции нет: под ней та же тональная база `CourseBackdrop`,
 * что под программой, тарифами и FAQ. Под секцию в этом слое добавлено своё
 * пятно — иначе она легла бы на голый тон, как до этого ложились слайд 6 и
 * слайд 8 (см. комментарий там же).
 *
 * `z-10` стоит на самой секции, а не на внутреннем контейнере: слой фона
 * лежит на `z-[3]` поверх потока и непрозрачен. Грабля, на которую в этом
 * проекте наступали пять раз.
 *
 * Сход в `bg-pitch` переехал сюда из FAQ: он всегда должен быть у последней
 * секции страницы, иначе гасит фон на стыке двух. Четвёртый переезд этого
 * слоя — до FAQ он жил в тарифах, до них в «Как проходит обучение», а ещё
 * раньше в «Программе».
 */

// Bebas инлайновым стилем, а не утилитой font-[...]: имя шрифта с пробелами
// Tailwind как arbitrary-значение не разбирает. Так же сделано в «Авторе
// обучения», «Как проходит обучение», тарифах и FAQ.
const BEBAS: CSSProperties = { fontFamily: '"Bebas Neue Cyrillic", "Bahnschrift", sans-serif' }

/** Синий акцент страницы. */
const ACCENT = '#6AA0FF'

export function QuoteSection() {
  return (
    <section id="quote" aria-label="Цитата автора обучения" className="relative z-10 px-5 pb-8">
      {/* Сход в bg-pitch перед подвалом — у последней секции страницы. */}
      <div
        aria-hidden="true"
        className="pointer-events-none absolute inset-x-0 bottom-0 -z-10 h-28 bg-[linear-gradient(180deg,transparent_0%,rgba(5,8,11,.55)_58%,#05080b_100%)]"
      />

      {/* Волосяная линия сверху — та же, что делит вопросы FAQ (white/[.07]).
          Ею секция цепляется за список над собой: цитата читается последней
          строкой того же списка, только вместо вопроса в ней говорит человек.
          Без линии блок начинался с пустоты и выглядел вброшенным. */}
      <span aria-hidden="true" className="block h-px bg-white/[.07]" />

      <figure className="relative pl-3.5 pt-7">
        {/* Синяя нить слева — приём FAQ: там она метит раскрытый вопрос.
            Здесь метит прямую речь. Ширина 2px и то же затухание книзу, что
            у нити в аккордеоне; отступ pl-3.5 — тоже оттуда. */}
        <span
          aria-hidden="true"
          style={{ backgroundImage: `linear-gradient(180deg,${ACCENT} 0%,${ACCENT}66 62%,transparent 100%)` }}
          className="absolute bottom-2 left-0 top-6 w-[2px] rounded-full"
        />

        {/* Врезка объявлена до текста: обтекание работает только если элемент
            с float стоит в потоке раньше обтекающего текста.

            Рамки и скругления нет намеренно. Ниже тарифов на странице нет ни
            одной рамки: FAQ построен на волосяных линиях и воздухе, и
            карточка с обводкой посреди этого читалась вброшенной картинкой —
            замечание владельца. Вместо края — растворение по левой и нижней
            грани, тем же приёмом, что снимки слайдов 2 и 3.

            Кадр уходит в вылет к правому краю экрана (-mr-5): у растворённого
            снимка не должно быть поля, иначе оно и работает краем. */}
        <span className="float-right -mr-5 mb-3 ml-4 block w-[44%] [mask-composite:intersect] [mask-image:linear-gradient(90deg,transparent_0,#000_40px),linear-gradient(180deg,#000_0,#000_calc(100%_-_56px),transparent_100%)] [-webkit-mask-composite:source-in] [-webkit-mask-image:linear-gradient(90deg,transparent_0,#000_40px),linear-gradient(180deg,#000_0,#000_calc(100%_-_56px),transparent_100%)]">
          <img
            src={coachBand}
            alt=""
            aria-hidden="true"
            loading="lazy"
            // Отношение, а не жёсткая высота: при фиксированной высоте кадр
            // на узком экране зумится сильнее — грабля «Автора обучения».
            // brightness ниже единицы: снимок с прожекторами ярче всего, что
            // осталось на этом этаже страницы, и в полную силу он спорил с
            // тихим FAQ над собой.
            className="aspect-[150/186] w-full select-none object-cover object-[70%_38%] brightness-[.86]"
          />
        </span>

        <blockquote className="text-[15px] leading-[1.58] text-white/85">
          {/* Кавычку рисует вёрстка, в тексте её нет: иначе она попадёт в
              копипаст и в микроразметку, когда та появится. Кегль 30px, а не
              46: рядом с капслоком 17px крупнее знак читается элементом
              оформления, а не частью строки. */}
          <span
            aria-hidden="true"
            style={{ ...BEBAS, color: ACCENT }}
            className="float-left mr-1.5 mt-[2px] text-[30px] leading-[.72] opacity-70"
          >
            «
          </span>
          {QUOTE.text}
        </blockquote>

        {/* Подпись набрана ровно как вопрос FAQ: Bebas-капслок 17px с
            трекингом 1px. Роль — мелким разрядкой, как надзаголовки секций.
            clear-both закрывает обтекание: без него подпись заезжает под
            врезку, если текст кончился раньше неё. */}
        <figcaption className="clear-both flex flex-wrap items-baseline gap-x-3 gap-y-1 pt-6">
          <span style={BEBAS} className="text-[17px] uppercase leading-none tracking-[1px] text-[#EAF2FF]">
            {QUOTE.author}
          </span>
          <span className="text-[10px] uppercase leading-none tracking-[.2em] text-white/45">{QUOTE.role}</span>
        </figcaption>
      </figure>
    </section>
  )
}
