import type { AudienceCard } from '../data/audience'

/**
 * Карточка сегмента в ленте «Для кого?» — постер (вариант 09 с макетной
 * `/audience.html`): кадр занимает всю площадь, текст лежит поверх по
 * затемнению. Прежняя карточка (вариант 02) делила площадь между кадром
 * 150px и телом с текстом — фотография выходила меньше половины карточки,
 * а высоту задавал самый длинный заголовок. Здесь кадр работает во всю
 * высоту, а текст ничего не раздвигает.
 *
 * Заглушки на месте недостающего кадра здесь больше нет: 30 августа
 * заказчик прислал недостающую фотографию любительских команд, снимки есть у
 * всех четырёх сегментов (Q6 закрыт).
 *
 * Высота фиксированная, а не по содержимому: у постера текст лежит абсолютно,
 * тянуть карточку ему нечем. 370px хватает самому длинному сегменту
 * (заголовок в три строки плюс четыре строки описания) с запасом.
 *
 * Прилипание по началу (`snap-start`), а не по центру: в покое карточка
 * стоит у левого поля, и `snap-center` после каждой прокрутки утаскивал её
 * обратно к центру — кнопки «вперёд/назад» двигали ленту на 15px вместо 280
 * и она выглядела заклинившей. Поле возвращает `scroll-pl-5` у ленты.
 *
 * Ширина фиксированная, а не долевая: карточка должна не помещаться в экран
 * целиком — край соседней виден и подсказывает пальцу, что ленту можно
 * листать. На 360px под ленту остаётся 320px, из них 268 занимает карточка,
 * и 52px «подглядывания» остаётся даже на самом узком телефоне.
 */
export function AudienceItem({ card }: { card: AudienceCard }) {
  return (
    <li className="relative h-[370px] w-[268px] shrink-0 snap-start overflow-hidden rounded-2xl border border-white/12 bg-panel">
      <img
        src={card.image}
        alt={card.alt}
        loading="lazy"
        style={{
          objectPosition: card.position,
          transform: card.zoom ? `scale(${card.zoom})` : undefined,
        }}
        className="absolute inset-0 h-full w-full object-cover"
      />

      {/* Затемнение под текстом. Первая версия (transparent 20% → .72 на 58%)
          не держала текст: описание ложилось на лицо и куртку героя и на
          светлых участках кадра пропадало. Здесь тень набирает плотность
          раньше и доходит до почти сплошного тона — верхние 24% кадра всё
          так же чистые, а нижняя половина работает подложкой, а не вуалью.
          Стопы подняты после выравнивания текста по верхней отметке: он
          начинается на 46% высоты, и к этому месту тень должна успеть
          набрать плотность. */}
      <div
        aria-hidden="true"
        className="absolute inset-0 bg-[linear-gradient(180deg,transparent_20%,rgba(5,9,14,.62)_44%,rgba(4,7,11,.92)_62%,rgba(3,6,9,.98)_100%)]"
      />

      {/* Текст прижат к отметке 172px сверху, а не к низу карточки.
          Прижатый к низу блок начинался у каждой карточки на своей высоте:
          замер давал 177, 194, 215 и 177px — у «Тренеров профессиональных
          команд» текст самый короткий, и он уезжал вниз почти на 40px
          относительно соседей. Теперь верх у всех общий, а разной остаётся
          длина хвоста, которую и так не с чем сравнивать.

          172px — это 370 минус самый высокий блок (192px: заголовок в три
          строки плюс пять строк описания) и ещё 6px запаса на случай, если
          Bebas не успел загрузиться и строка сверстается запасным шрифтом. */}
      <div className="absolute inset-x-0 bottom-0 top-[172px] p-4">
        {/* Номера сегмента на карточке нет: снят по просьбе владельца. Поле
            `num` в данных остаётся — оно служит ключом списка и на него
            опираются макетные страницы в src/dev. */}
        <h3 className="section-title text-[17px] uppercase leading-[1.06] tracking-title">
          {card.title}
        </h3>
        {/* 13px, а не 11.5px как в макетной: на постере текст лежит на
            фотографии, и мелкий кегль там теряется сильнее, чем на панели.
            13px — нижняя граница для основного текста на мобильном по
            app-чеклисту ui-ux-pro-max. */}
        <p className="mt-2 text-[13px] leading-[1.5] text-white/85">{card.detail}</p>
      </div>
    </li>
  )
}
