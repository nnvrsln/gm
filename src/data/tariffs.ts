/**
 * Тарифы — слайд 6 ТЗ «Выбери свой тариф».
 *
 * Источник: `docs/tz/02-TARIFFS.md` (расшифровка листа «ТАРИФЫ» из таблицы
 * заказчика). Читать надо именно расшифровку, а не CSV: в исходной таблице
 * «не входит в тариф» показано **зачёркиванием**, а при экспорте в CSV
 * зачёркивание пропадает — и получается, что в СТАНДАРТ входит всё.
 *
 * Заказчик про подачу сказал дословно: «в файле по ссылке внизу это все
 * сделано в формате таблицы, чтобы ты не запутался, но на самом сайте
 * тарифы идут отдельными столбцами, при этом нужно выделить цветом 2-ой
 * тариф и добавить туда значок звездочки и слово: ХИТ, чтобы отразить, что
 * именно этот тариф самый популярный (нам надо его продавать)».
 *
 * ── Что здесь решено и почему ────────────────────────────────────────────
 *
 * **Названия приведены к одному виду.** В таблице одна и та же позиция
 * называется по-разному, и на сайте это читалось бы как разные вещи:
 *   — «ГРУППОВЫЕ РАЗБОРЫ ТРЕНИРОВОК ОТ ГАДЖИ ГАДЖИЕВА МУСЛИМОВИЧА» в
 *     СТАНДАРТЕ против «РАЗБОРЫ ТРЕНИРОВОК» в ПРЕМИУМ и ВИП — берём
 *     короткое (Q23, ждём подтверждения);
 *   — «ЖИВАЯ-ВСТРЕЧА» через дефис в двух ячейках — правильно без дефиса;
 *   — порядок имени: «ГАДЖИЕВЫМ ГАДЖИ МУСЛИМОВИЧЕМ» (Фамилия Имя Отчество),
 *     как в слайдах 1 и 3, а не «ГАДЖИ ГАДЖИЕВЫМ МУСЛИМОВИЧЕМ».
 *
 * **Описания не сочиняются.** Девять позиций сетки дословно совпадают с
 * фишками слайда 5 — у них стоит `learningKey`, и текст берётся из
 * `data/learning.ts`, то есть из того же ТЗ. У остальных описания нет, и
 * выдумывать его нельзя: в сетке только названия.
 *
 * **Модули 1–5 входят во все три тарифа.** В матрице сравнения это пять
 * строк подряд с одинаковыми галочками — чистый шум. Поэтому у них стоит
 * `group: 'modules'`, и раскладка вправе свернуть их в одну строку
 * (`MATRIX_FOLDED`). Данные при этом остаются полными: карточка тарифа
 * может перечислить модули поимённо.
 *
 * TODO (Q18): три кнопки ведут «в вотсап со стартовым сообщением» — ни
 * номера, ни текстов заказчик не дал. `WHATSAPP_NUMBER` пуст, тексты в
 * `CONTACT_LINKS` — наше предложение из `03-QUESTIONS.md`.
 * TODO (Q19): кнопки оплаты — заглушки, бэкенда в этой версии нет.
 * TODO (Q23): два вопроса самого заказчика висят прямо в данных, у них
 * стоит флаг `pending` — см. `PENDING_NOTES` внизу файла.
 */

/** Идентификаторы колонок. Порядок — порядок цены, он же порядок таблицы. */
export type TariffId = 'standard' | 'premium' | 'vip'

export type Tariff = {
  id: TariffId
  /** Название капслоком — как в таблице. */
  name: string
  /** Цена числом: форматирует `formatPrice`, чтобы пробел был неразрывный. */
  price: number
  /**
   * «Хит» — второй тариф. Прямое требование ТЗ: цветовое выделение +
   * звёздочка + слово «ХИТ». Флаг один на три тарифа и должен таким
   * остаться: два выделенных тарифа не выделяют ни одного.
   */
  hit?: boolean
  /**
   * Свой цвет тарифа. Требование владельца: «у каждого столбца свой цвет,
   * придумай аналогию цвета к названию».
   *
   * Аналогия — материал ступени, а не случайный оттенок. Тарифы идут по
   * возрастанию, и по возрастанию идёт материал: сталь → сигнальный синий →
   * золото. Ни один цвет не выдуман под этот слайд, все три уже работают на
   * странице и означают там ровно то же самое:
   *   — **сталь `#9FB4CC`** — базовая ступень, точка отсчёта. Единственный
   *     из трёх, который не цвет, а его отсутствие: СТАНДАРТ не должен
   *     выглядеть предложением, он должен выглядеть началом отсчёта;
   *   — **синий `#6AA0FF`** — акцент всей страницы, самый громкий цвет
   *     сайта. Достаётся тому тарифу, который «нам надо продавать»;
   *   — **золото `#FFC14A`** — на странице уже означает «сверх основного»:
   *     им помечен бонусный модуль в «Программе» и «что остаётся после» в
   *     слайде 5. ВИП — ровно это.
   *
   * Красного в этой шкале нет и быть не может: решение 30.08 — красный на
   * странице не используем вовсе.
   *
   * Порядок в массиве = порядок ступени: `TARIFFS.indexOf` даёт номер
   * ступени для индикатора, отдельного поля под него не заводим.
   */
  accent: string
}

