/**
 * Деньги курса — единственный источник правды для страницы и для сервера.
 *
 * ── Зачем отдельный пакет ────────────────────────────────────────────────
 * Цена живёт в двух мирах: на кнопке тарифа и в счёте, который выставляет
 * бэкенд. Если её продублировать, однажды заказчик поднимет цену, поправят
 * одно место из двух, и человек увидит на странице одну сумму, а в платёжке
 * другую. Это самая дорогая ошибка из возможных, поэтому числа лежат здесь,
 * а `apps/web` и `apps/api` их только читают.
 *
 * Здесь **нет** ничего про оформление: цвета тарифов, состав, порядок строк
 * сравнения и подписи кнопок остаются в `apps/web/src/data/tariffs.ts`.
 * Серверу они не нужны, а пакет, который тянут обе стороны, должен быть
 * настолько мал, насколько возможно.
 *
 * ── Единицы ──────────────────────────────────────────────────────────────
 * Хранение — в рублях: так цены записаны в ТЗ и в тарифной таблице
 * заказчика, и так их проверяют глазами. Платёжки считают в копейках,
 * поэтому перевод сделан один раз в `toKopecks` и на стороне сервера
 * руками не повторяется.
 *
 * Источник чисел: `docs/tz/02-TARIFFS.md`.
 */

/** Идентификаторы тарифов. Порядок — порядок цены, он же порядок таблицы. */
export type TariffId = 'standard' | 'premium' | 'vip'

/**
 * Что человек делает с заказом: платит целиком или бронирует место.
 * Из таблицы тарифов — «ОПЛАТИТЬ ПОЛНОСТЬЮ» и «ЗАБРОНИРОВАТЬ ЗА 10 000 ₽».
 */
export type PayAction = 'full' | 'reserve'

/**
 * Кортеж, а не массив: из него строится проверка входа на сервере, и
 * литеральные типы должны сохраниться, иначе `tariffId` выродится в
 * `string` и мимо валидации пройдёт любая строка.
 */
export const TARIFF_ORDER = ['standard', 'premium', 'vip'] as const satisfies readonly TariffId[]

export const TARIFF_NAMES: Record<TariffId, string> = {
  standard: 'Стандарт',
  premium: 'Премиум',
  vip: 'ВИП',
}

/** Цены в рублях. `docs/tz/02-TARIFFS.md`, раздел «Три тарифа». */
export const TARIFF_PRICES: Record<TariffId, number> = {
  standard: 49_900,
  premium: 64_900,
  vip: 99_900,
}

/**
 * Сумма брони. Из ТЗ: «бронь места за 10 000 рублей» (слайд 8, ответ 2) и
 * «ЗАБРОНИРОВАТЬ ЗА 10 000 ₽» в таблице тарифов. Число одно на весь проект:
 * подпись кнопки, строка «внесёте сейчас» в листе оплаты, расчёт остатка и
 * сумма счёта считают его отсюда.
 */
export const RESERVE_AMOUNT = 10_000

export function isTariffId(value: unknown): value is TariffId {
  return typeof value === 'string' && value in TARIFF_PRICES
}

export function isPayAction(value: unknown): value is PayAction {
  return value === 'full' || value === 'reserve'
}

/** Рубли → копейки. Цены целые, дробей здесь не бывает. */
export function toKopecks(rubles: number) {
  return Math.round(rubles * 100)
}

/**
 * Суммы заказа в копейках.
 *
 * `total` — стоимость тарифа целиком, она хранится в заказе всегда, даже при
 * броне: без неё не посчитать остаток к доплате.
 * `charge` — сколько человек платит **сейчас**, на этом шаге.
 *
 * Считает только сервер. Клиент присылает `{ tariffId, action }` и никогда
 * не присылает рубли — иначе цену курса можно поправить в консоли браузера.
 */
export function orderAmounts(tariffId: TariffId, action: PayAction) {
  const total = toKopecks(TARIFF_PRICES[tariffId])
  const charge = action === 'reserve' ? toKopecks(RESERVE_AMOUNT) : total

  return { total, charge, remainder: total - charge }
}
