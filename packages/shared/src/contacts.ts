/**
 * Проверки контактных полей — общие для формы и для сервера.
 *
 * Лежат здесь по той же причине, что и цены: если правила разъедутся,
 * получится худший из возможных сценариев — форма на странице говорит
 * «всё верно», а сервер тот же самый ввод отклоняет. Человек видит ошибку
 * там, где ошибки нет, и уходит.
 *
 * Формат телефона задан маской в `usePhoneMask`, и сервер обязан принимать
 * ровно её результат: +7(999)000-00-00.
 */

/** Российский номер под маской формы: +7(999)000-00-00. */
export const PHONE_RE = /^\+7\(\d{3}\)\d{3}-\d{2}-\d{2}$/

/**
 * Почта. Проверка намеренно нестрогая: полная грамматика адреса из RFC
 * отсекает живые адреса чаще, чем мёртвые, а настоящая проверка — это
 * письмо, которое дойдёт. Кириллица в домене допускается: .рф существует.
 */
export const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[A-Za-zА-Яа-я]{2,}$/

/** Ник в Telegram, с собакой или без. Длина — по правилам самого Telegram. */
export const TELEGRAM_RE = /^@?[A-Za-z0-9_]{5,32}$/

/** Ник без ведущей собаки — в таком виде он хранится и уезжает в CRM. */
export function normalizeTelegram(value: string) {
  return value.trim().replace(/^@/, '')
}
